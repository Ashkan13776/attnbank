"""Merge the per-family bibliography snippets into attnbank/references.bib.

The library is expanded by several contributors at once and a single shared
.bib is the reliable way to lose entries to a bad merge. Each family owns
``bib/<family>.bib``; this concatenates them deterministically and refuses to
write when two snippets define the same key with different content.

    python tools/merge_bib.py           # write attnbank/references.bib
    python tools/merge_bib.py --check   # exit 1 if it is out of date (for CI)
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BIB_DIR = ROOT / "bib"
OUT = ROOT / "attnbank" / "references.bib"

ENTRY = re.compile(r"^@(\w+)\s*\{\s*([^,\s]+)\s*,", re.M)


def split_entries(text: str) -> list[tuple[str, str]]:
    """Return [(key, source)] by brace matching, so nested braces survive."""
    out, i = [], 0
    for m in ENTRY.finditer(text):
        key, start, depth = m.group(2), m.start(), 0
        for i in range(m.end() - 1, len(text)):
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
                if depth == 0:
                    out.append((key, text[start:i + 1]))
                    break
    return out


def build() -> tuple[str, list[str]]:
    seen: dict[str, tuple[str, str]] = {}   # key -> (source, file)
    problems: list[str] = []
    for path in sorted(BIB_DIR.glob("*.bib")):
        for key, src in split_entries(path.read_text()):
            if key in seen and _norm(seen[key][0]) != _norm(src):
                problems.append(
                    f"{key}: defined differently in {seen[key][1]} and {path.name}")
            seen.setdefault(key, (src, path.name))
    body = "\n\n".join(src for _, (src, _) in sorted(seen.items()))
    header = ("% GENERATED by tools/merge_bib.py from bib/*.bib -- do not edit.\n"
              f"% {len(seen)} entries.\n\n")
    return header + body + "\n", problems


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", s).strip()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if references.bib is out of date")
    args = ap.parse_args()

    if not BIB_DIR.exists():
        print(f"no {BIB_DIR}", file=sys.stderr)
        return 1
    text, problems = build()
    for p in problems:
        print(f"conflict: {p}", file=sys.stderr)
    if problems:
        return 1

    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("references.bib is out of date; run tools/merge_bib.py",
                  file=sys.stderr)
            return 1
        print(f"references.bib up to date ({text.count('@')} entries)")
        return 0

    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} with {len(split_entries(text))} entries")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
