def rewrite_nav(oracles: tuple) -> None:
    path = ROOT / "mkdocs.yml"
    text = path.read_text()
    if NAV_BEGIN not in text or NAV_END not in text:
        raise SystemExit(
            f"mkdocs.yml is missing the nav markers.\n  {NAV_BEGIN}\n  {NAV_END}")
    block = ["  - Browse the bank:", "      - methods/index.md"]
    for cat in (c.value for c in Category):
        names = ab.available(cat)
        if not names:
            continue
        block.append(f"      - {cat}:")
        for n in names:
            label = f"{n} (oracle)" if n in oracles else n
            block.append(f"          - {label}: methods/{n}.md")
    head, _, rest = text.partition(NAV_BEGIN)
    _, _, tail = rest.partition(NAV_END)
    path.write_text(head + NAV_BEGIN + "\n" + "\n".join(block) + "\n" + NAV_END + tail)
    print("rewrote the nav block in mkdocs.yml")


