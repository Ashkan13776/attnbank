def extras_keys(name: str) -> list[str]:
    """What this method actually puts in ``extras`` -- observed, not declared."""
    import torch

    cls = ab.get_class(name)
    torch.manual_seed(0)
    q, k, v = (torch.randn(1, 2, 32, 16) for _ in range(3))
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        out = ab.build(name)(q, k, v, causal=cls.supports_causal, return_weights=True)
    return sorted(out.extras)


def backend_reason(name: str, extras: list[str]) -> str:
    """Why this method declares ``reference`` only -- derived, never guessed.

    The first two branches read the method's own ``extras``: a method that reports the
    omitted mass, or the exact and perturbed score matrices, has already said that it
    needs the dense scores. The fall-through is the category argument of
    ``docs/backends.md``.
    """
    cat = ab.get_class(name).category.value
    if "eps" in extras:
        return ("it reports the omitted mass `eps` (and the $\\chi^2$ divergence of the "
                "renormalisation) in `extras`, which needs the full score matrix. A "
                "kernel that avoids materialising that matrix is a kernel that cannot "
                "produce them.")
    if {"s", "s_hat"} <= set(extras):
        return ("it returns both the exact and the perturbed score matrices (`s`, "
                "`s_hat`) in `extras` — the perturbation *is* the object of study, and "
                "a fused kernel hands back neither.")
    return CATEGORY_KERNEL[cat]


def anchor_block(name: str, info) -> list[str]:
    cls = ab.get_class(name)
    conv = cls.convergence_configs()
    out: list[str] = []
    if info.limit_config == {}:
        out += [
            "This method is **exact as built**: the conformance suite instantiates it "
            "at its default config and requires both `y` and the weights to match "
            "`softmax`. `limit_config()` returns `{}` — the empty dict, not `None`: "
            "there is a limit and no setting has to be changed to reach it.",
        ]
    elif info.limit_config:
        cfg = ", ".join(f"`{key}={val!r}`" for key, val in info.limit_config.items())
        out += [
            "**Exact limit.** Built with " + cfg + " this method provably *is* dense "
            "softmax, and `tests/test_conformance.py` asserts it — output and weights, "
            "float32 and float64.",
            "",
            "```pycon",
            f'>>> ab.describe("{name}").limit_config',
            repr(info.limit_config),
            "```",
        ]
    if conv:
        out += [
            "",
            "**Convergence anchor.** There is no finite resource at which this method "
            "is exact, so the anchor is monotonicity instead: the mean error against "
            "`softmax` must decrease along these configs, and the suite fails if it "
            "does not.",
            "",
            "```pycon",
            f'>>> ab.get_class("{name}").convergence_configs()',
            repr(conv),
            "```",
        ]
    if not out:
        out += [
            "**None, and that is the declaration.** `objective = modify` means this is "
            "a different operator, not an approximation of softmax, so neither anchor "
            "applies. The conformance suite does not skip the check — it *asserts the "
            "exemption*, requiring `limit_config()` and `convergence_configs()` to both "
            "be `None` for a `modify` method.",
        ]
    return out


def cost_block(name: str) -> list[str]:
    cls = ab.get_class(name)
    src = textwrap.dedent(inspect.getsource(cls.cost)).rstrip()
    here = ab.build(name).cost(**COST_SHAPE)
    ref = ab.build("softmax").cost(**COST_SHAPE)
    shape = ", ".join(f"${key} = {val}$" for key, val in COST_SHAPE.items())
    rows = ["| quantity | this method | `softmax` | ratio |", "|---|---:|---:|---:|"]
    for key in ("flops", "state_bytes", "bytes_moved"):
        if key not in here:
            continue
        a, b = float(here[key]), float(ref.get(key, 0.0))
        ratio = f"{a / b:.3g}×" if b else "—"
        rows.append(f"| `{key}` | {a:,.0f} | {b:,.0f} | {ratio} |")
    return [
        "Analytic, per `(batch, head)`, declared by the method itself:",
        "",
        "```python",
        src,
        "```",
        "",
        f"At {shape} and `bytes_per_el=2`, against the reference operator at the same "
        "shape:",
        "",
        *rows,
        "",
        '!!! note "A cost model is not a benchmark"',
        "    These are counted operations and resident bytes, not measured time.",
        "    They are what the monograph's capacity arguments are made of;",
        "    `examples/08_cost_and_capacity.py` walks through the comparison properly.",
    ]


def bibtex_block(keys, bib: dict) -> list[str]:
    """The cited entries, verbatim, inside a closed `<details>`.

    Raw HTML rather than a fenced block on purpose: a fence would pick up Material's
    own code-copy button as well as the one `docs/javascripts/clip.js` adds, and two
    buttons that do almost the same thing is worse than none. Closed, and inside a
    disclosure, so the page reads the same as it did; open, and it is the bibliography
    itself -- which is what a reader with scripting off selects by hand, there being no
    button for them to press.
    """
    entries = [(key, bib[key]["_source"]) for key in keys
               if bib.get(key, {}).get("_source")]
    if not entries:                                     # pragma: no cover - CI gate
        return []
    plural = "entry" if len(entries) == 1 else "entries"
    # ``no-copy`` is the theme's own opt-out: ``content.code.copy`` is on, and
    # mkdocs-material mounts a copy button on every ``pre > code`` it finds. Two
    # buttons on one block, one of them overlapping the other, is worse than either.
    out = [
        '<details class="attn-bib no-copy">',
        f'<summary>BibTeX — {len(entries)} {plural}, verbatim from '
        '<code>attnbank/references.bib</code></summary>',
        '<div class="attn-bib__entries">',
    ]
    for key, src in entries:
        out += [f'<div class="attn-bib__entry" data-bibkey="{key}">',
                f'<pre class="attn-bib__src"><code>{_escape(src)}</code></pre>',
                "</div>"]
    return out + ["</div>", "</details>"]


def related_block(name: str, oracles: tuple) -> list[str]:
    """Methods related to this one, by the two axes the registry actually has.

    Same `category` is *changes the same object*; same `objective` is *judged the same
    way*. Both lists are `ab.available(...)` with this method removed, so there is no
    hand-written "see also" to go stale -- and no third axis, because the registry does
    not have one. A method in both lists is named once, under the category: the
    stronger relation of the two.
    """
    cls = ab.get_class(name)
    cat, obj = cls.category.value, cls.objective.value
    same_cat = [n for n in ab.available(cat) if n != name]
    same_obj = [n for n in ab.available(objective=obj)
                if n != name and n not in same_cat]
    if not same_cat and not same_obj:                   # pragma: no cover - CI gate
        return []

    def links(names) -> str:
        return ", ".join(f"[`{n}`]({n}.md)" + (" *(oracle)*" if n in oracles else "")
                         for n in names)

    out = [
        "## Related methods",
        "",
        "Two relations, because the registry declares two axes: what a method changes, "
        "and what it is trying to be. Both lists are "
        f"`ab.available(...)` with `{name}` removed.",
        "",
    ]
    if same_cat:
        out += [
            f"changes the same object — [`{cat}`](../taxonomy.md#{cat})",
            f":   {links(same_cat)}"
            f" &nbsp;·&nbsp; [browse the bank, {cat} only](index.md?category={cat})",
            "",
        ]
    if same_obj:
        beyond = ", beyond the ones above" if same_cat else ""
        out += [
            f"judged the same way — `{obj}`{beyond}",
            f":   {links(same_obj)}"
            f" &nbsp;·&nbsp; [browse the bank, {obj} only](index.md?objective={obj})",
            "",
        ]
    out += [
        f"[Open the browser with `{name}` selected](index.md?compare={name}) and tick up "
        "to three more to see them in columns. Every row there is one the registry "
        "declares, and the rows the selected methods agree on fold away.",
        "",
    ]
    return out


