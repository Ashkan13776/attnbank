def _detex(s: str) -> str:
    s = re.sub(r"\{\\[\"'`^~=.]\{?(\w)\}?\}", r"\1", s)    # {\"o} -> o
    s = re.sub(r"\\&", "&", s)
    s = s.replace("{", "").replace("}", "").replace("--", "–")
    return " ".join(s.split())


def parse_bib(path: Path) -> dict[str, dict]:
    """``{key: {field: value}}``. A small brace-counting reader; no bibtex dependency.

    ``_source`` is the entry exactly as it stands in the file. The copy-BibTeX control
    hands that text to the clipboard, so what a reader pastes into their own ``.bib``
    is the packaged bibliography byte for byte -- not this parser's idea of it.
    """
    text = path.read_text(errors="ignore")
    entries: dict[str, dict] = {}
    for match in re.finditer(r"@(\w+)\s*\{\s*([^,]+),", text):
        start = match.end()
        depth, i = 1, start
        while i < len(text) and depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        body = text[start:i - 1]
        fields = {}
        for fmatch in re.finditer(r"(\w+)\s*=\s*", body):
            j = fmatch.end()
            if j >= len(body):
                continue
            if body[j] == "{":
                depth, start_v = 1, j + 1
                j += 1
                while j < len(body) and depth:
                    depth += {"{": 1, "}": -1}.get(body[j], 0)
                    j += 1
                fields[fmatch.group(1).lower()] = body[start_v:j - 1]
            elif body[j] == '"':
                end = body.find('"', j + 1)
                fields[fmatch.group(1).lower()] = body[j + 1:end]
            else:
                end = body.find(",", j)
                fields[fmatch.group(1).lower()] = body[j:end if end > 0 else len(body)]
        entries[match.group(2).strip()] = {
            "_type": match.group(1), "_source": text[match.start():i], **fields}
    return entries


def _surname(author_field: str) -> str:
    first = _detex(author_field).split(" and ")[0].strip()
    if "," in first:
        return first.split(",")[0].strip()
    return first.split()[-1] if first.split() else first


def citation(key: str, entry: dict | None) -> str:
    """One Markdown list item: ``Surname et al. (year). *Title*. Venue. [arXiv:…]``."""
    if entry is None:                                       # pragma: no cover - CI gate
        return f"- `{key}` — **not found in `attnbank/references.bib`**"
    authors = _detex(entry.get("author", "")).split(" and ")
    who = _surname(entry.get("author", "")) or key
    if len(authors) == 2:
        who = f"{who} and {_surname(authors[1])}"
    elif len(authors) > 2:
        who = f"{who} et al."
    year = _detex(entry.get("year", "n.d."))
    title = _detex(entry.get("title", key))
    venue = _detex(entry.get("booktitle") or entry.get("journal")
                   or entry.get("howpublished") or "")
    links = []
    if entry.get("eprint"):
        eid = _detex(entry["eprint"])
        links.append(f"[arXiv:{eid}](https://arxiv.org/abs/{eid})")
    if entry.get("doi"):
        doi = _detex(entry["doi"])
        links.append(f"[doi:{doi}](https://doi.org/{doi})")
    bits = [f"**{who} ({year}).**", f"*{title}.*"]
    if venue and not venue.lower().startswith("arxiv preprint"):
        bits.append(venue + ".")
    if links:
        bits.append(" ".join(links))
    return ("- " + " ".join(bits)
            + f'<br><span class="attn-cite" data-bibkey="{key}"><code>{key}</code>'
            + "</span>")


