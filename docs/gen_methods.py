def _search_text(name: str, info, oracles: tuple) -> str:
    words = [name, display_name(name), info.class_name, info.category, info.objective,
             info.paper_section, summary_text(info.summary),
             *info.backends, *info.references,
             *(key for key in info.parameters if key not in _PLUMBING)]
    if info.supports_causal:
        words.append("causal")
    else:
        words += ["not causal", "non-causal"]
    if info.trainable:
        words.append("trainable")
    if name in oracles:
        words += ["oracle", "upper bound"]
    if not info.row_stochastic:
        words += ["signed", "not stochastic", "not row-stochastic"]
    if len(info.backends) > 1:
        words.append("fused kernel")
    return " ".join(words).lower().replace('"', " ")


