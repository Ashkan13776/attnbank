def example_source(name: str, info) -> str:
    cls = ab.get_class(name)
    kwargs = {key: val for key, val in info.parameters.items()
              if key not in _PLUMBING and val is not None}
    kwargs = dict(list(kwargs.items())[:2])
    call = ", ".join([f'"{name}"'] + [f"{key}={val!r}" for key, val in kwargs.items()])
    causal = cls.supports_causal
    note = "" if causal else "   # it declares supports_causal = False"
    src = [
        "import torch, attnbank as ab",
        "",
        "torch.manual_seed(0)",
        "b, h, n, d = " + ", ".join(str(x) for x in EX_SHAPE),
        "q, k, v = (torch.randn(b, h, n, d) for _ in range(3))",
        "",
        f"attn = ab.build({call})",
        f"out = attn(q, k, v, causal={causal},{note}",
        "           return_weights=True)",
        "",
        "print(attn)",
        "print(out)",
        'print("invariant W:", out.check_invariant(v))',
    ]
    if cls.objective is Objective.ACCELERATE:
        src += [
            "",
            "# objective = accelerate: the claim is equality with the reference, so that",
            "# is what the example checks.",
            f'y_ref = ab.attend("softmax", q, k, v, causal={causal})',
            'print("max |y - y_softmax|:", float((out.y - y_ref).abs().max()))',
        ]
    elif cls.objective is Objective.APPROXIMATE:
        cfg = {key: val for key, val in kwargs.items() if key not in ("mode", "score")}
        src += [
            "",
            "# objective = approximate: it targets dense softmax, so it is judged by",
            "# output error -- split into the distributional and value terms.",
            f'row = ab.compare(["{name}"], q, k, v, causal={causal},',
            f'                 configs={{"{name}": {cfg!r}}})[0]',
            'print({key: round(row[key], 5) for key in',
            '       ("output_error", "distributional_error", "value_error", "tv")})',
        ]
    else:
        src += [
            "",
            "# objective = modify: this is a different operator and fidelity to softmax",
            "# is not its goal, so there is no error to quote. What it *is* doing shows",
            "# up in its own diagnostics.",
            'print("row_stochastic =", attn.row_stochastic, "| first row sums:",',
            "      [round(x, 4) for x in out.weights.sum(-1)[0, 0, :4].tolist()])",
            'print("extras:", sorted(out.extras))',
        ]
    return "\n".join(src)


def run_example(src: str) -> str:
    """Execute the snippet and return everything it printed, warnings included."""
    buf = io.StringIO()
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        with contextlib.redirect_stdout(buf):
            exec(compile(src, "<example>", "exec"), {"__name__": "__main__"})  # noqa: S102
    out = buf.getvalue().rstrip("\n")
    for w in caught:
        out += f"\n{w.category.__name__}: {w.message}"
    return out


