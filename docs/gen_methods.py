def _fence_blocks(text: str) -> str:
    """Fence RST literal blocks: runs of indented lines that *start* a paragraph.

    ``gen_gallery`` fences every indented run, which is right for the example scripts.
    The method docstrings also wrap enumerations onto indented continuation lines
    (``nystrom``'s three caveats), so here a block must be preceded by a blank line to
    count as a display.
    """
    out: list[str] = []
    block: list[str] = []
    prev_blank = True
    for line in text.split("\n") + [""]:
        indented = line.startswith("    ")
        if block and (indented or not line.strip()):
            block.append(line[4:] if indented else line)
            continue
        if block:
            while block and not block[-1].strip():
                block.pop()
            out += ["```text", *block, "```", ""]
            block = []
            prev_blank = True
        if indented and prev_blank:
            block = [line[4:]]
            continue
        out.append(line)
        prev_blank = not line.strip()
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


def _dashes(text: str) -> str:
    """``--`` is a dash in the docstrings: em between words, en inside one.

    Code spans are left alone — ``a--b`` inside backticks is usually an argument.
    """
    parts = text.split("`")
    for i in range(0, len(parts), 2):          # even indices are outside backticks
        parts[i] = re.sub(r"(?<=\s)--(?=\s)", "—", parts[i])
        parts[i] = re.sub(r"(?<=\w)--(?=\w)", "–", parts[i])
    return "`".join(parts)


def rst_to_md(text: str) -> str:
    text = re.sub(r"``([^`]+)``", r"`\1`", text)
    # any Sphinx role, not only :class: -- the method docstrings also use :func:
    text = re.sub(r":\w+:`~?([^`]+)`", r"`\1`", text)
    text = re.sub(r"::\s*$", ":", text, flags=re.M)
    text = _enumerations(text)
    return _dashes(_fence_blocks(text))


def _enumerations(text: str) -> str:
    """``(1) …`` at the start of a line is a list in the docstring; make it one here.

    Markdown would otherwise run the items together into a single paragraph, which is
    how ``nystrom``'s three caveats read before this.
    """
    if not re.search(r"^\(1\) ", text, flags=re.M):
        return text
    out = []
    for line in text.split("\n"):
        match = re.match(r"^\((\d+)\) (.*)$", line)
        if match:
            if out and out[-1].strip():
                out.append("")
            out.append(f"{match.group(1)}. {match.group(2)}")
        else:
            out.append(line)
    return "\n".join(out)


def display_name(name: str) -> str:
    """The method's human name, taken from the first words of its module docstring.

    Every lede is written as ``Name: what it does.`` -- ``FlashAttention: tiled online
    softmax``, ``H2O: accumulated-attention heavy-hitter eviction`` -- with the three
    oracles putting the ``ORACLE:`` marker in front of the same shape. That convention
    is what gives the browser a name to lead each row with; ``flash`` and ``evict_h2o``
    are registry keys, which is a different thing and is shown underneath.

    The split is asserted, not guessed. A lede that does not carry a name fails the
    build rather than quietly putting a sentence fragment in the name column.
    """
    lede, _ = module_doc(name)
    lede = re.sub(r"^ORACLE:\s*", "", lede)              # the oracle banner says it
    lede = re.sub(r"\s*\(`sec:[^)]*\)\s*\.?$", "", lede)   # trailing section pointers
    head, sep, tail = lede.partition(":")
    head = head.strip()
    if not sep or not tail.strip() or not 1 <= len(head.split()) <= 6:
        raise SystemExit(
            f"{name}: the module docstring's first line must read "
            f"'Name: what it does.' so the browser has a name to show for the "
            f"'{name}' key. Got:\n  {lede}")
    return head


def summary_html(text: str) -> str:
    """A one-line docstring summary as HTML, for the browser table cells."""
    return re.sub(r"``([^`]+)``", r"<code>\1</code>", _dashes(_escape(text)))


def summary_text(text: str) -> str:
    """The same summary with the RST markup stripped, for the search index."""
    return re.sub(r"``([^`]+)``", r"\1", text)


def module_doc(name: str) -> tuple[str, str]:
    """``(lede, body)`` of the method module's docstring, minus its ``Reference:`` tail.

    The tail is dropped because this page renders the bibliography entries themselves,
    with links, further down; keeping both would be the same claim twice.
    """
    mod = sys.modules[ab.get_class(name).__module__]
    doc = (mod.__doc__ or "").strip()
    lines = doc.split("\n")
    lede = lines[0].strip()
    body = "\n".join(lines[1:]).strip()
    body = re.split(r"^Reference:", body, flags=re.M)[0].rstrip()
    return rst_to_md(lede), rst_to_md(body)


