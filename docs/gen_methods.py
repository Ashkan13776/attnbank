"""Regenerate ``docs/methods/`` -- one page per registered method, plus the browser.

    python docs/gen_methods.py

Nothing on those pages is written by hand. Every sentence comes from one of four
places, and the generator refuses to invent a fifth:

* the **registry** -- ``ab.describe``, ``ab.backend_matrix``, ``cost()``,
  ``limit_config()`` / ``convergence_configs()``, the ``__init__`` signature;
* the **module docstring** of the method, which was written to be read against the
  monograph and already carries the operator in the paper's notation;
* the packaged **bibliography**, ``attnbank/references.bib``, for the citations;
* the method **running**, here, now: every example on every page was executed by this
  script and its output pasted back in, and the ``extras`` keys a method actually
  returns are what decides how its backend row is explained.

The only prose that lives in this file is :data:`CHANGES` and :data:`CATEGORY_KERNEL`
-- one sentence per *category*, not per method -- which is the same arrangement
``gen_taxonomy.py`` uses for its category blurbs.

The script also rewrites the ``Browse the bank`` block of ``mkdocs.yml`` in place,
between two marker comments, so a new method appears in the nav without anyone
remembering to add it.
"""
