def _objective_sentence(obj: str) -> str:
    return {
        "accelerate": "It pursues **acceleration**: the operator is the reference "
                      "operator, exact up to floating point. The only question worth "
                      "asking of it is *where* exactness stops.",
        "approximate": "It pursues **approximation**: it is trying to be dense "
                       "softmax, so it is fair to judge it by output error, and it "
                       "must supply a correctness anchor saying where it becomes "
                       "exact.",
        "modify": "It pursues **modification**: it defines a *different* operator. "
                  "Asking how closely it approximates softmax is asking the wrong "
                  "question — it is not trying to.",
    }[obj]


