SOURCE_ORDER = ("gpt2/wikitext103", "qwen2.5-0.5b/wikitext103", "synthetic")

HEADER = ("%% generated by attnbank.studies.tables from lib/results/{src}.json\n"
          "%% do not edit by hand; re-run `python -m attnbank.studies.tables`\n"
          "%% git commit of the run: {commit}\n")


def num(x, nd: int = 2, dash: str = "---") -> str:
    """Fixed-decimal cell, so a column of them is decimal-aligned under ``r``."""
    try:
        v = float(x)
    except (TypeError, ValueError):
        return dash
    if v != v or v in (float("inf"), float("-inf")):
        return dash
    return f"{v:.{nd}f}"


def sci(x, nd: int = 1, dash: str = "---") -> str:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return dash
    if v != v or v == 0:
        return "0" if v == 0 else dash
    m, e = f"{v:.{nd}e}".split("e")
    return f"${m}\\times 10^{{{int(e)}}}$"


def intc(x, dash: str = "---") -> str:
    try:
        return f"{int(round(float(x))):,}"
    except (TypeError, ValueError):
        return dash


def pct(x, nd: int = 0, dash: str = "---") -> str:
    try:
        return f"{100 * float(x):.{nd}f}"
    except (TypeError, ValueError):
        return dash


def mnum(x, nd: int = 2, dash: str = "---") -> str:
    """A number for running prose: wrapped in math mode so a minus sign is a minus."""
    t = num(x, nd, dash)
    return t if t == dash else f"${t}$"


def ci(block, nd: int = 3, dash: str = "---") -> str:
    """``slope`` with its 95% CI, both at the same precision."""
    try:
        s = float(block["slope"])
        lo, hi = float(block["ci95"][0]), float(block["ci95"][1])
    except (TypeError, ValueError, KeyError):
        return dash
    if s != s:
        return dash
    return f"${s:+.{nd}f}$ $[{lo:+.{nd}f}, {hi:+.{nd}f}]$"


# The Foundations and Trends text block is 118mm (~4.65in) wide -- a good deal
# narrower than the 6.5in these tables were first laid out for, and every one of
# them overflowed it.  Rather than scale the tables (which would put the digits
# below legibility) each ``tabular`` is emitted at ``\\footnotesize`` with a
# tightened ``\\tabcolsep``.  Only the type size changes; no cell, column or
# number is touched, so the provenance of every figure is unaffected.
_TAB_OPEN = "{\\footnotesize\\setlength{\\tabcolsep}{4pt}%\n\\begin{tabular}"


def fit_narrow(body: str) -> str:
    """Wrap every ``tabular`` in the body so it fits the FnT text block."""
    return (body.replace("\\begin{tabular}", _TAB_OPEN)
                .replace("\\end{tabular}", "\\end{tabular}}"))


def write(name: str, body: str, src: str, commit: str) -> Path:
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"{name}.tex"
    path.write_text(HEADER.format(src=src, commit=commit) + fit_narrow(body))
    return path


def load(tag: str):
    p = H.load_results(tag)
    return p["meta"]["summary"], p["meta"]


